/**
 * Builds the two private Kaggle kernels (as single Python script sources):
 *
 * - **prepare** (run once): quantize the reasoner to GPTQ W4A16, build
 *   llama-server for SM75, cache the MedGemma GGUFs → kernel output.
 * - **serve** (every session): attach the prepare output and run
 *   `cloud_bootstrap.sh` (vLLM + llama.cpp + router + cloudflared).
 *
 * Remote assets ship in `../remote/` and are embedded base64, so one
 * `SaveKernel` call carries everything. Settings travel as a base64 JSON
 * environment block — no shell or Python quoting of user values anywhere.
 *
 * @module @deepseek-ai/dsh-medical-cloud/kernels
 */

import { readFileSync } from 'node:fs'

export const REMOTE_DIR = new URL('../remote/', import.meta.url)

export function readRemoteAsset(name: 'cloud_bootstrap.sh' | 'router.py' | 'prepare.py'): string {
  return readFileSync(new URL(name, REMOTE_DIR), 'utf8')
}

/** The only serve-time knobs automated remediation may change. */
export interface Knobs {
  mode: 'auto' | 'dual' | 'single'
  maxModelLen: number
  gpuMemUtil: number
  maxNumSeqs: number
  visionCtx: number
  enforceEager: boolean
}

export interface ServeSettings extends Knobs {
  reasonerName: string
  visionName: string
  vllmVersion: string
  cloudflaredVersion: string
  cloudflaredSha256: string
  visionGgufUrl: string
  visionMmprojUrl: string
  idleTimeoutSeconds: number
  maxSessionSeconds: number
  bootTimeoutSeconds: number
}

export interface PrepareSettings {
  reasonerHf: string
  llamaCppRef: string
  visionGgufUrl: string
  visionMmprojUrl: string
  calibrationSamples: number
}

export function serveEnv(settings: ServeSettings, token: string): Record<string, string> {
  return {
    SESSION_BEARER_TOKEN: token,
    REASONER_NAME: settings.reasonerName,
    VISION_NAME: settings.visionName,
    VLLM_VERSION: settings.vllmVersion,
    CLOUDFLARED_VERSION: settings.cloudflaredVersion,
    CLOUDFLARED_SHA256: settings.cloudflaredSha256,
    VISION_GGUF_URL: settings.visionGgufUrl,
    VISION_MMPROJ_URL: settings.visionMmprojUrl,
    MEDHARNESS_MODE: settings.mode,
    MAX_MODEL_LEN: String(settings.maxModelLen),
    GPU_MEM_UTIL: String(settings.gpuMemUtil),
    MAX_NUM_SEQS: String(settings.maxNumSeqs),
    VISION_CTX: String(settings.visionCtx),
    ENFORCE_EAGER: settings.enforceEager ? '1' : '0',
    IDLE_TIMEOUT: String(settings.idleTimeoutSeconds),
    MAX_SESSION: String(settings.maxSessionSeconds),
    BOOT_TIMEOUT: String(settings.bootTimeoutSeconds),
  }
}

export function prepareEnv(settings: PrepareSettings): Record<string, string> {
  return {
    REASONER_HF: settings.reasonerHf,
    LLAMA_CPP_REF: settings.llamaCppRef,
    VISION_GGUF_URL: settings.visionGgufUrl,
    VISION_MMPROJ_URL: settings.visionMmprojUrl,
    CALIB_SAMPLES: String(settings.calibrationSamples),
  }
}

const b64 = (s: string): string => Buffer.from(s, 'utf8').toString('base64')

function wrapper(kind: string, files: Record<string, string>, env: Record<string, string>, entry: string[]): string {
  const fileTable = Object.entries(files).map(([name, body]) => `    ${JSON.stringify(name)}: "${b64(body)}",`).join('\n')
  return `# medharness ${kind} kernel — generated by @deepseek-ai/dsh-medical-cloud. Do not edit.
# PRIVATE: this source carries a per-session secret. Never make this kernel public.
import base64, json, os, subprocess, sys

FILES = {
${fileTable}
}
ENV = json.loads(base64.b64decode("${b64(JSON.stringify(env))}").decode("utf-8"))

work = "/tmp/medharness"
os.makedirs(work, exist_ok=True)
for name, data in FILES.items():
    path = os.path.join(work, name)
    with open(path, "wb") as f:
        f.write(base64.b64decode(data))
    os.chmod(path, 0o700)

env = dict(os.environ)
env.update(ENV)
env["MEDHARNESS_WORK"] = work
env["PYTHONUNBUFFERED"] = "1"
sys.exit(subprocess.call(${JSON.stringify(entry)}, env=env, cwd=work))
`
}

export function buildServeKernel(settings: ServeSettings, token: string, assets = {
  bootstrap: readRemoteAsset('cloud_bootstrap.sh'),
  router: readRemoteAsset('router.py'),
}): string {
  return wrapper('serve', { 'cloud_bootstrap.sh': assets.bootstrap, 'router.py': assets.router }, serveEnv(settings, token), ['bash', '/tmp/medharness/cloud_bootstrap.sh'])
}

export function buildPrepareKernel(settings: PrepareSettings, prepare = readRemoteAsset('prepare.py')): string {
  return wrapper('prepare', { 'prepare.py': prepare }, prepareEnv(settings), ['python3', '/tmp/medharness/prepare.py'])
}

// ---------------------------------------------------------------------------
// Log protocol
// ---------------------------------------------------------------------------

export type LogEvent =
  | { kind: 'stage'; name: string }
  | { kind: 'ready'; url: string; mode?: string | undefined }
  | { kind: 'prepared' }
  | { kind: 'failed'; stage: string; reason: string }
  | { kind: 'stopped'; reason: string }

const TRYCLOUDFLARE = /^https:\/\/[a-z0-9-]+\.trycloudflare\.com$/

/** Parse one kernel log line into a protocol event (or nothing). */
export function parseLogLine(line: string): LogEvent | undefined {
  const text = line.trim()
  let m = /^MEDHARNESS_STAGE name=(\S+)/.exec(text)
  if (m) return { kind: 'stage', name: m[1] as string }
  m = /^MEDHARNESS_READY url=(\S+)(?:.*\bmode=(\w+))?/.exec(text)
  if (m) {
    // Only accept a Cloudflare quick-tunnel origin: the URL comes from a log, so treat it as untrusted.
    return TRYCLOUDFLARE.test(m[1] as string) ? { kind: 'ready', url: m[1] as string, mode: m[2] } : { kind: 'failed', stage: 'tunnel', reason: 'unexpected tunnel URL' }
  }
  if (/^MEDHARNESS_PREPARED\b/.test(text)) return { kind: 'prepared' }
  m = /^MEDHARNESS_FAILED stage=(\S+) reason=(.*)$/.exec(text)
  if (m) return { kind: 'failed', stage: m[1] as string, reason: (m[2] as string).slice(0, 500) }
  m = /^MEDHARNESS_STOPPED reason=(.*)$/.exec(text)
  if (m) return { kind: 'stopped', reason: (m[1] as string).slice(0, 200) }
  return undefined
}
